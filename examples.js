function useExample(i) {
  if (
    busy ||
    !examples[i] ||
    (dirty && !confirm("작업 중인 내용을 닫고 예시 프로젝트를 열까요?"))
  )
    return;
  clearTimeout(timer);
  clearEditor();
  const ex = examples[i];
  for (const k of fields) $(k).value = ex[k] || "";
  const lesson = { title: ex.title, detail: ex.plan, stimulus: ex.plan };
  const d = defaultDesign(snapshot(), lesson, 0);
  for (const k of ["goal", "question", "success", "supplies"]) d[k] = ex[k];
  d.stages = ex.rows.map(
    ([name, time, action, prompt, evidence, example], i) => ({
      ...d.stages[i],
      name,
      time,
      action,
      prompt,
      evidence,
      example,
    }),
  );
  lesson.design = d;
  lessons = [lesson];
  activeLesson = 0;
  renderLessons();
  markChanged();
  showPanel("materials");
  status(
    "가상 수업 예시를 열었습니다. 편집 후 새 프로젝트로 저장할 수 있습니다.",
  );
}
